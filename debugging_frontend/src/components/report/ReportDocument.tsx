import { SEVERITY } from "@/domain/severity";
import type { ReportFinding, ReportModel } from "@/domain/report";
import { DefectDetails } from "@/components/DefectDetails";
import { PhotoImage } from "@/components/ui/PhotoImage";
import { SeveritySwatch } from "@/components/ui/SeveritySwatch";

/**
 * On-screen rendering of a report.
 *
 * Built from the same `ReportModel` the exported HTML is built from, so what
 * the inspector approves on screen is what lands in the downloaded file.
 */
export function ReportDocument({
  model,
  plates,
}: {
  model: ReportModel;
  /** Annotated plate images by index, or `null` while they are still rendering. */
  plates: (string | null)[] | null;
}) {
  return (
    <article className="px-6 pt-8 pb-11 sm:px-11">
      <header className="mb-5 border-b-2 border-ink pb-3.5">
        <h1 className="mb-1 text-[17px] font-semibold">Physical inspection report</h1>
        <p className="text-xs text-ink-muted">Returned unit — visual defect analysis</p>
      </header>

      <dl className="mb-6 grid grid-cols-2 gap-3.5 sm:grid-cols-4">
        <Meta label="Run" value={model.runId} mono />
        <Meta label="Completed" value={model.completedAt} mono />
        <Meta label="Product line" value={model.line.name} />
        <Meta label="Model" value={model.line.model} mono />
        <Meta label="Photos" value={String(model.totals.photos)} mono />
        <Meta label="Regions flagged" value={String(model.totals.regions)} mono />
        <Meta label="Critical" value={String(model.totals.critical)} mono />
        <Meta label="Disposition" value={model.disposition.label} />
      </dl>

      {model.plates.map((plate, index) => (
        <section key={plate.photo.id} className="mb-6 border-b border-rule pb-5.5">
          <h2 className="mb-2.5 text-xs font-semibold">
            Plate {index + 1} — {plate.photo.name}
          </h2>

          {plates?.[index] ? (
            <PhotoImage
              src={plates[index]}
              alt={`Annotated ${plate.photo.name}`}
              className="mb-3 block max-w-full border border-rule-strong"
            />
          ) : (
            <p className="mb-3 text-2xs text-ink-faint">Rendering annotated image…</p>
          )}

          {plate.findings.length === 0 ? (
            <p className="text-xs text-ink-muted">No defects detected on this view.</p>
          ) : (
            plate.findings.map((finding) => <Finding key={finding.detectionId} finding={finding} />)
          )}
        </section>
      ))}

      <p className="text-2xs leading-relaxed text-ink-faint">
        Generated by FA-Bench from model {model.line.model}. Detections are advisory; a technician
        confirms the disposition before the unit leaves the bay.
      </p>
    </article>
  );
}

function Meta({ label, value, mono = false }: { label: string; value: string; mono?: boolean }) {
  return (
    <div>
      <dt className="mb-0.5 text-2xs text-ink-faint">{label}</dt>
      <dd className={mono ? "font-mono text-xs font-medium numeric" : "text-xs font-medium"}>
        {value}
      </dd>
    </div>
  );
}

function Finding({ finding }: { finding: ReportFinding }) {
  const severity = SEVERITY[finding.defect.severity];

  return (
    <div className="mb-3.5">
      <div className="mb-1 flex items-center gap-2">
        <SeveritySwatch severity={finding.defect.severity} />
        <span className="flex-1 font-medium">
          {finding.position} · {finding.defect.name}
        </span>
        <span className="font-mono text-2xs text-ink-faint numeric">
          {severity.label} · {(finding.confidence * 100).toFixed(1)}%
        </span>
      </div>
      <DefectDetails defect={finding.defect} className="pl-4" />
    </div>
  );
}
