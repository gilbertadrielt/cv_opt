import { SEVERITY } from "@/domain/severity";
import type { ReportFinding, ReportModel, ReportPlate } from "@/domain/report";
import { escapeHtml } from "./escape-html";

/**
 * Serialises a report into one self-contained HTML file.
 *
 * Everything is inlined — styles in a `<style>` block, annotated plates as
 * base64 data URLs — so the file can be attached to an RMA ticket and opened
 * anywhere without the app, a network, or any sibling assets.
 */

const DOCUMENT_STYLES = `
 body { font: 14px/1.55 'IBM Plex Sans', system-ui, sans-serif; color: #22282A; max-width: 820px; margin: 40px auto; padding: 0 26px; }
 h1 { font-size: 18px; margin: 0 0 4px; }
 h2 { font-size: 13px; margin: 0 0 9px; }
 .head { border-bottom: 2px solid #22282A; padding-bottom: 12px; margin-bottom: 18px; }
 .head p { margin: 0; font-size: 12px; color: #5C6668; }
 .meta { display: grid; grid-template-columns: repeat(4, 1fr); gap: 12px; margin-bottom: 26px; font-size: 12.5px; }
 .meta span { display: block; color: #8B9496; font-size: 11px; }
 section { border-bottom: 1px solid #D3D5D0; padding-bottom: 20px; margin-bottom: 22px; }
 img { max-width: 100%; border: 1px solid #C2C5BF; display: block; margin-bottom: 12px; }
 .finding { margin-bottom: 14px; }
 .finding-name { margin: 0 0 4px; font-weight: 500; }
 .swatch { display: inline-block; width: 8px; height: 8px; margin-right: 6px; vertical-align: middle; }
 .desc { margin: 0 0 6px; color: #5C6668; font-size: 13px; }
 .impact-head { margin: 0 0 3px; color: #8B9496; font-size: 11.5px; }
 ul { margin: 0 0 10px; padding-left: 16px; font-size: 13px; }
 .mono { font-family: 'IBM Plex Mono', ui-monospace, monospace; }
 .footnote { font-size: 12px; color: #8B9496; }
 @media print { body { margin: 0; } section { break-inside: avoid; } }
`;

function renderFinding(finding: ReportFinding): string {
  const severity = SEVERITY[finding.defect.severity];
  const impacts = finding.defect.impacts
    .map((impact) => `<li>${escapeHtml(impact)}</li>`)
    .join("");

  return `<div class="finding">
      <p class="finding-name">
        <span class="swatch" style="background:${severity.hex}"></span>
        <b>${finding.position} · ${escapeHtml(finding.defect.name)}</b>
        — ${escapeHtml(severity.label)} · ${(finding.confidence * 100).toFixed(1)}%
      </p>
      <p class="desc">${escapeHtml(finding.defect.description)}</p>
      ${impacts ? `<p class="impact-head">What it causes in service</p><ul>${impacts}</ul>` : ""}
    </div>`;
}

function renderPlate(plate: ReportPlate, index: number, image: string | null): string {
  const findings = plate.findings.map(renderFinding).join("");

  return `<section>
      <h2>Plate ${index + 1} — ${escapeHtml(plate.photo.name)}</h2>
      ${image ? `<img src="${escapeHtml(image)}" alt="Annotated ${escapeHtml(plate.photo.name)}">` : ""}
      ${findings || '<p class="desc">No defects detected on this view.</p>'}
    </section>`;
}

function metaCell(label: string, value: string, mono = false): string {
  return `<div><span>${escapeHtml(label)}</span><b${mono ? ' class="mono"' : ""}>${escapeHtml(value)}</b></div>`;
}

/** `plates[i]` is the annotated data URL for `model.plates[i]`, or null if it could not be rendered. */
export function buildReportHtml(model: ReportModel, plates: readonly (string | null)[]): string {
  const sections = model.plates
    .map((plate, index) => renderPlate(plate, index, plates[index] ?? null))
    .join("");

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(model.runId)} — Physical inspection report</title>
<style>${DOCUMENT_STYLES}</style>
</head>
<body>
<div class="head">
  <h1>Physical inspection report</h1>
  <p>Returned unit — visual defect analysis</p>
</div>
<div class="meta">
  ${metaCell("Run", model.runId, true)}
  ${metaCell("Completed", model.completedAt, true)}
  ${metaCell("Product line", model.line.name)}
  ${metaCell("Model", model.line.model, true)}
  ${metaCell("Photos", String(model.totals.photos), true)}
  ${metaCell("Regions flagged", String(model.totals.regions), true)}
  ${metaCell("Critical", String(model.totals.critical), true)}
  ${metaCell("Disposition", model.disposition.label)}
</div>
${sections}
<p class="footnote">
  Generated by FA-Bench from model ${escapeHtml(model.line.model)}. Detections are advisory;
  a technician confirms the disposition before the unit leaves the bay.
</p>
</body>
</html>`;
}
